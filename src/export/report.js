/* Markdown case report. Every indicator is defanged. */
import { SEV_ORDER, SEV_LABEL } from '../data.js';
import { fmtDur } from '../format.js';
import { defang } from './iocs.js';

export function reportMD(r){
  const L = []; const p = (...x) => L.push(...x);
  const md = v => String(v == null ? '' : v).replace(/\|/g,'\\|').replace(/\n/g,' ');
  const utc = d => d ? d.toISOString().replace(/\.\d+Z$/,'Z') : '-';
  // Defang free text: hostnames, IPv4 addresses, and @. A name followed by '=' is a header key (header.from=), not a host.
  const dfx = t => String(t).replace(/\b((?:[a-z0-9-]+\.)+[a-z]{2,})\b(?!=)/gi, m => m.replace(/\./g,'[.]'))
    .replace(/\b\d{1,3}(?:\.\d{1,3}){3}\b/g, m => m.replace(/\./g,'[.]')).replace(/@/g,'[@]');
  p(`# Email X-Ray case report: ${r.caseId}`, '');
  p(`- Scanned: ${r.scannedAt}`, `- Verdict: ${r.verdict} (${r.score}/100)`, `- Raw email SHA-256: ${r.rawSha256 || 'n/a'}`, `- Size: ${r.rawSize} bytes`, '');
  p('## Message', `- Subject: ${r.subject || '(none)'}`, `- From: ${r.from ? (r.from.name ? `${r.from.name} <${defang('email', r.from.addr)}>` : defang('email', r.from.addr)) : '(none)'}`);
  if (r.replyTo) p(`- Reply-To: ${defang('email', r.replyTo.addr)}`);
  if (r.retPath) p(`- Return-Path: ${defang('email', r.retPath.addr)}`);
  p(`- To: ${r.to || '(none)'}`, `- Date: ${r.date || '(none)'}`, '');
  p('## Findings');
  [...r.F].sort((a,b) => SEV_ORDER[a.sev] - SEV_ORDER[b.sev]).forEach(f => p(`- [${SEV_LABEL[f.sev]}] ${dfx(f.title)}${f.detail ? '. ' + dfx(f.detail) : ''}`));
  if (r.cues.length) p(`- Pressure language: ${r.cues.map(c => `${c.label} ("${c.match}")`).join('; ')}`);
  p('', '## Delivery path (origin first)', '', '| # | From (HELO) | IP | rDNS | By | Protocol | Time (UTC) | Delta |', '|---|---|---|---|---|---|---|---|');
  r.hops.forEach((h,i) => p(`| ${i+1}${i === r.originIdx ? ' (origin)' : ''} | ${md(h.from ? dfx(h.from) : '-')} | ${md(h.ip ? defang('ipv4', h.ip) : '-')} | ${md(h.rdns ? dfx(h.rdns) : '-')} | ${md(h.by ? dfx(h.by) : '-')} | ${md(h.proto || '-')} | ${utc(h.date)} | ${h.delay != null ? fmtDur(h.delay) : '-'} |`));
  p('', '## Authentication', `- SPF: ${r.auth.spf || 'not reported'}`, `- DKIM: ${r.auth.dkim || 'not reported'}${r.auth.dkimD.length ? ' (d=' + dfx(r.auth.dkimD.join(', ')) + ')' : ''}`, `- DMARC: ${r.auth.dmarc || 'not reported'}`, '', '```', r.arRaw ? dfx(r.arRaw) : 'Authentication-Results: (not present)', '```', '');
  p(`## Links (${r.links.length})`);
  r.links.forEach(l => { p(`- ${defang('url', l.href)}${l.shown && l.shown !== l.href ? ` (displayed as: ${dfx(l.shown)})` : ''}`); l.flags.forEach(([sev,t]) => p(`  - [${SEV_LABEL[sev]}] ${dfx(t)}`)); });
  p('', `## Attachments (${r.atts.length})`);
  r.atts.forEach(a => { p(`- ${a.name} (${a.type}, ${a.size} bytes)`, `  - SHA-256: ${a.sha256 || 'n/a'}`, `  - SHA-1: ${a.sha1 || 'n/a'}`, `  - MD5: ${a.md5 || 'n/a'}`); a.flags.forEach(([sev,t]) => p(`  - [${SEV_LABEL[sev]}] ${t}`)); });
  p('', '## MITRE ATT&CK');
  if (!r.attack.length) p('- No techniques mapped.');
  r.attack.forEach(t => p(`- ${t.id} ${t.name}: ${t.why}`));
  p('', '## Indicators (defanged)', '', '| Type | Value | Seen in |', '|---|---|---|');
  r.iocs.forEach(i => p(`| ${i.type} | ${md(defang(i.type, i.value))} | ${md(i.context)} |`));
  if (r.ai) p('', '## AI analysis', '', r.ai);
  p('', '---', 'Generated by Email X-Ray. Indicators are defanged. Automated analysis; verify before acting on it.');
  return L.join('\n');
}
